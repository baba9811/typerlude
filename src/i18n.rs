pub fn initial_ui_language(lc_all: Option<&str>, lang: Option<&str>) -> Language {
    let locale = lc_all.or(lang).unwrap_or_default();
    let prefix = locale.split(['_', '-', '.']).next().unwrap_or_default();
    if prefix.eq_ignore_ascii_case("ko") {
        Language::Ko
    } else {
        Language::En
    }
}
